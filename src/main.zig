const std = @import("std");

const Machine = @import("machine.zig");

const Io = std.Io;
const Prng = std.Random.DefaultPrng;

const clock = Io.Clock.real;

pub fn main(init: std.process.Init) !void {
    var prng: Prng = initPrng(init.io);

    const program = [_]u8{
        0x60, 0x00, // Set V0 = 0x00
        0xF0, 0x29, // Set I = font sprite for V0
        0x61, 0x02, // Set V1 = 0x02
        0x62, 0x01, // Set V2 = 0x01
        0xD1, 0x25, // Draw VX = V1, VY = V2, N = 5

        0x70, 0x01, // Set V0 += 0x01
        0xF0, 0x29, // Set I = font sprite for V0
        0x71, 0x05, // Set V1 += 0x05
        0xD1, 0x25, // Draw VX = V1, VY = V2, N = 5

        0x70, 0x01,
        0xF0, 0x29,
        0x71, 0x05,
        0xD1, 0x25, //

        0x70, 0x01,
        0xF0, 0x29,
        0x71, 0x05,
        0xD1, 0x25, //

        0x70, 0x01,
        0xF0, 0x29,
        0x71, 0x05,
        0xD1, 0x25, //

        0x70, 0x01,
        0xF0, 0x29,
        0x71, 0x05,
        0xD1, 0x25, //

        0x70, 0x01,
        0xF0, 0x29,
        0x71, 0x05,
        0xD1, 0x25, //

        0x70, 0x01,
        0xF0, 0x29,
        0x71, 0x05,
        0xD1, 0x25, //

        // Move to next line
        0x61, 0x02, // Set V1 = 0x02
        0x72, 0x06, // Set V2 += 0x06

        0x70, 0x01,
        0xF0, 0x29,
        // 0x71, 0x05,
        0xD1, 0x25, //

        0x70, 0x01,
        0xF0, 0x29,
        0x71, 0x05,
        0xD1, 0x25, //

        0x70, 0x01,
        0xF0, 0x29,
        0x71, 0x05,
        0xD1, 0x25, //

        0x70, 0x01,
        0xF0, 0x29,
        0x71, 0x05,
        0xD1, 0x25, //

        0x70, 0x01,
        0xF0, 0x29,
        0x71, 0x05,
        0xD1, 0x25, //

        0x70, 0x01,
        0xF0, 0x29,
        0x71, 0x05,
        0xD1, 0x25, //

        0x70, 0x01,
        0xF0, 0x29,
        0x71, 0x05,
        0xD1, 0x25, //

        0x70, 0x01,
        0xF0, 0x29,
        0x71, 0x05,
        0xD1, 0x25, //

        0xC3, 0xFF, // Set V3 = rand & 0xFF
    };

    var machine: Machine = .init(&program, &prng);
    for (0..program.len / 2) |_| machine.execute(.decode(machine.read()));

    std.debug.print("{f}\n", .{&machine});
    std.debug.print("Rand: {}", .{machine.v[3]});
}

/// Initialize an `std.Random.DefaultPrng` instance seeded with the current time.
fn initPrng(io: Io) Prng {
    return .init(@bitCast(clock.now(io).toMicroseconds()));
}
